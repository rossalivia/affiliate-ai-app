// Simple helpers for future sections
export function getModuleById(moduleId: string): Module | undefined {
  return curriculum.modules.find((m) => m.id === moduleId);
}

export function getMaterialById(materialId: string): Material | undefined {
  for (const module of curriculum.modules) {
    const found = module.materials.find((m) => m.id === materialId);
    if (found) return found;
  }
  return undefined;
}

// Development-time validation check
export function validateCurriculum(data: Curriculum = curriculum): {
  isValid: boolean;
  errors: string[];
} {
  const errors: string[] = [];
  const moduleIds = new Set<string>();
  const materialIds = new Set<string>();

  data.modules.forEach((mod, modIdx) => {
    // Check module ID uniqueness
    if (!mod.id || moduleIds.has(mod.id)) {
      errors.push(`Duplicate or missing module ID: "${mod.id}" at index ${modIdx}`);
    }
    moduleIds.add(mod.id);

    // Check module order
    if (mod.order !== modIdx + 1) {
      errors.push(`Module order mismatch: "${mod.id}" has order ${mod.order}, expected ${modIdx + 1}`);
    }

    mod.materials.forEach((mat, matIdx) => {
      // Check material ID uniqueness
      if (!mat.id || materialIds.has(mat.id)) {
        errors.push(`Duplicate or missing material ID: "${mat.id}" in module "${mod.id}"`);
      }
      materialIds.add(mat.id);

      // Check material order
      if (mat.order !== matIdx + 1) {
        errors.push(`Material order mismatch: "${mat.id}" has order ${mat.order}, expected ${matIdx + 1}`);
      }

      // Check URL and resourceType
      if (!mat.url || mat.url.trim() === '') {
        errors.push(`Empty URL for material "${mat.id}" in module "${mod.id}"`);
      }

      const validTypes = ['youtube', 'youtube-short', 'google-drive', 'google-docs', 'gemini'];
      if (!validTypes.includes(mat.resourceType)) {
        errors.push(`Invalid resourceType "${mat.resourceType}" for material "${mat.id}"`);
      }
    });
  });

  return {
    isValid: errors.length === 0,
    errors,
  };
}
